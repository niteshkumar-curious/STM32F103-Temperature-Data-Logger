void SSD1306_Init(void)
{
  
    static const uint8_t init_cmds[]={
        0xAE,       // display off
        0xA8, 0x1F, // set MUX Ratio
        0xD3, 0x00, // set display offset
        0x40,       // set dispaly start line
        0xA0,        // set segment re-map
        0xC0,       // set com scan direction
        0xDA, 0x02,  // set com pins hardware config
        0x81, 0x7F,  // set contrast
        0xA4,        // disable entire display on
        0xA6,       // set normal display
        0xD5, 0x80, // set osc freq
        0x8D, 0x14, // enable charge pump
        0x20, 0x00, // set memory address mode
        0xAF,       // display on

    };
    
    I2C_WriteCommand(init_cmds, sizeof(init_cmds));
}

void OLED_Display_clear(void)
{
	for(uint16_t i=0;i<SSD1306_BUFFER_SIZE;i++)
	{
		FrameBuffer[i]= 0x00;
	}
}

static void FrameBuffer_DrawPixel(uint8_t x,uint8_t y,uint8_t color)
{
	if(x>= SSD1306_WIDTH || y>= SSD1306_HEIGHT) return;
	
	uint16_t index = x + ((y/8)*SSD1306_WIDTH);
	uint8_t bit_shift = y%8;
	
	if(color)
	{
		FrameBuffer[index] |= (1 << bit_shift); // pixel on
	}
	else
	{
		FrameBuffer[index] &= ~(1 << bit_shift); // pixel off
	}
	
}

static void FrameBuffer_DrawChar(uint8_t x, uint8_t y, char ch)
{
	
	if(ch < 32 || ch > 126) return;
	
	uint8_t font_index = ch-32;
	
	for(uint8_t col=0;col<5;col++)
	{
		
		uint8_t glyph_byte = Font5x7[font_index][col];
		for(uint8_t bit =0; bit<7;bit++)
		{
			uint8_t pixel_on = (glyph_byte >> bit) & 0x01;
			FrameBuffer_DrawPixel(x+col, y+bit, pixel_on);
		}
	}
}


void OLED_Display_Char(uint8_t x, uint8_t y, char ch)
{
    if((x + 5) > SSD1306_WIDTH)
    {
        x = 0;
        y += 8;
    }

    if(y >= SSD1306_HEIGHT)
    {
        return;
    }

    FrameBuffer_DrawChar(x, y, ch);
}


void OLED_Display_String(uint8_t x, uint8_t y, const char *str)
{
	uint8_t cursor_x = x;
	uint8_t cursor_y = y;
	while(*str)
	{
		if((cursor_x + 5) > SSD1306_WIDTH )
		{
			cursor_x = 0 ;
			cursor_y = cursor_y + 8;
		}
		
		if(cursor_y >= SSD1306_HEIGHT)
		{
			break;
		}
		
		FrameBuffer_DrawChar(cursor_x,cursor_y,*str);
		cursor_x += 6; // 5 pixel width + 1 spacing
		str++;
	}
	
}

void OLED_Display_Number(uint8_t x, uint8_t y, int32_t num)
{
	char buf[12];
	int i=0;
	
	if(num==0)
	{
		FrameBuffer_DrawChar(x,y,'0');
		return;
	}
	
	if(num < 0)
	{
		FrameBuffer_DrawChar(x,y,'-');
		x += 6;
		num = -num;
	}
	
	while(num > 0)
	{
		buf[i++] = (num % 10) + '0';
		num /= 10;
	}
	
	while(i>0)
	{
		FrameBuffer_DrawChar(x,y,buf[--i]);
		x += 6;
	}
	
}

void OLED_Display_Float(uint8_t x, uint8_t y, float num)
{
    int32_t int_part;
    int32_t dec_part;
    char buf[12];
    int i=0;

    if(num < 0.0f){

        FrameBuffer_DrawChar(x,y,'-');
        x += 6;
        num = -num;
    }

    int_part = (int32_t)num;

    dec_part = (int32_t)((num - int_part)*100 + 0.5f);

    if(dec_part > 100)
    {
        int_part++;
        dec_part =0;
    }

    if(int_part == 0)
    {
        FrameBuffer_DrawChar(x,y,'0');
        x += 6;
    }
    else
    {
        while(int_part > 0)
        {
            buf[i++] = (int_part % 10) + '0';
            int_part /= 10;
        }

        while(i>0)
        {
            FrameBuffer_DrawChar(x,y,buf[--i]);
            x += 6;
        }
    }

    FrameBuffer_DrawChar(x,y,'.');
    x += 6;

    FrameBuffer_DrawChar(x,y,(dec_part/10)+ '0');
    x += 6;

    FrameBuffer_DrawChar(x,y,(dec_part % 10) + '0');
}


void SSD1306_updateScreen(void)
{
	static const uint8_t rest_add_cmd[]={
		0x21, 0x00, 0x7F,  // set column 0-127
		0x22, 0x00, 0x03,  // set page 0-4
		};
	I2C_WriteCommand(rest_add_cmd,sizeof(rest_add_cmd));
		
		
	I2C_WriteData(FrameBuffer, SSD1306_BUFFER_SIZE);	
		
}
